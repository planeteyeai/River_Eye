const fs = require('fs')
const html = fs.readFileSync('mula-mutha-source.html', 'utf8')
const start = html.indexOf('<script id="fallback" type="application/json">')
const end = html.indexOf('</script>', start)
if (start < 0 || end < 0) {
  console.error('NO JSON')
  process.exit(1)
}
const raw = html.slice(start + '<script id="fallback" type="application/json">'.length, end)
const D = JSON.parse(raw)
fs.writeFileSync('mula-mutha-extracted.json', JSON.stringify(D, null, 2))

console.log('keys', Object.keys(D).join(', '))
console.log('generated', D.generated)
console.log('demo_notice', D.demo_notice)
console.log('kml_reach_id', D.kml_reach_id)
console.log('history_days', D.history_days)
console.log('forecast_days', D.forecast_days)
console.log('bod_edges', JSON.stringify(D.bod_edges))
console.log('class_colors', JSON.stringify(D.class_colors))
console.log('reaches', D.reaches.length)
D.reaches.forEach((r) => {
  console.log('---', r.id, r.name, 'km', r.km.join('-'), 'width_m', r.width_m)
  console.log('   villages:', r.villages)
  console.log('   today:', JSON.stringify(r.today))
  console.log('   hist n', r.history.dates.length, 'from', r.history.dates[0], 'to', r.history.dates.at(-1))
  console.log('   hist p50 first/last', r.history.p50[0], r.history.p50.at(-1))
  console.log('   fc n', r.forecast.dates.length, 'from', r.forecast.dates[0], 'to', r.forecast.dates.at(-1))
  console.log('   fc p50 first/last', r.forecast.p50[0], r.forecast.p50.at(-1))
})
console.log('alerts', D.alerts.length)
D.alerts.forEach((a) => console.log(JSON.stringify(a)))
console.log('blind_metrics', JSON.stringify(D.blind_metrics, null, 2))
console.log('skill', JSON.stringify(D.skill, null, 2))
console.log('landmarks', JSON.stringify(D.landmarks))
console.log('file bytes', fs.statSync('mula-mutha-extracted.json').size)
